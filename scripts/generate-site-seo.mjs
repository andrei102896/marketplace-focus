import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, extname, dirname, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const BASE_URL = "https://market-focus.andreiprojects.com";
const SITE_DIR = join(dirname(fileURLToPath(import.meta.url)), "..", "site");
const EXCLUDED_HTML_FILES = new Set(["404.html"]);

function toPosixPath(filePath) {
  return filePath.split(sep).join("/");
}

function discoverHtmlFiles(dir) {
  const entries = readdirSync(dir, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolutePath = join(dir, entry.name);

    if (entry.isDirectory()) {
      files.push(...discoverHtmlFiles(absolutePath));
      continue;
    }

    if (!entry.isFile() || extname(entry.name) !== ".html") {
      continue;
    }

    const relativePath = toPosixPath(relative(SITE_DIR, absolutePath));
    if (EXCLUDED_HTML_FILES.has(relativePath)) {
      continue;
    }

    files.push(absolutePath);
  }

  return files;
}

function routeFromHtmlPath(htmlPath) {
  const relativePath = toPosixPath(relative(SITE_DIR, htmlPath));
  const withoutExt = relativePath.replace(/\.html$/, "");

  if (withoutExt === "index") {
    return "/";
  }

  if (withoutExt.endsWith("/index")) {
    const route = withoutExt.replace(/\/index$/, "");
    return route === "" ? "/" : `/${route}`;
  }

  return `/${withoutExt}`;
}

function buildSitemapXml(routes) {
  const xmlUrls = routes
    .map(({ route, lastmod }) => {
      const isHomepage = route === "/";
      const loc = `${BASE_URL}${route === "/" ? "/" : route}`;
      const changefreq = isHomepage ? "weekly" : "monthly";
      const priority = isHomepage ? "1.0" : "0.6";

      return [
        "  <url>",
        `    <loc>${loc}</loc>`,
        `    <lastmod>${lastmod}</lastmod>`,
        `    <changefreq>${changefreq}</changefreq>`,
        `    <priority>${priority}</priority>`,
        "  </url>",
      ].join("\n");
    })
    .join("\n");

  return [
    "<?xml version=\"1.0\" encoding=\"UTF-8\"?>",
    "<!-- Auto-generated by scripts/generate-site-seo.mjs -->",
    "<urlset xmlns=\"http://www.sitemaps.org/schemas/sitemap/0.9\">",
    xmlUrls,
    "</urlset>",
    "",
  ].join("\n");
}

function buildRobotsTxt() {
  return [
    "# Auto-generated by scripts/generate-site-seo.mjs",
    "User-agent: *",
    "Allow: /",
    "",
    `Sitemap: ${BASE_URL}/sitemap.xml`,
    "",
  ].join("\n");
}

function sortRoutes(routes) {
  return routes.sort((a, b) => {
    if (a.route === "/") {
      return -1;
    }
    if (b.route === "/") {
      return 1;
    }
    return a.route.localeCompare(b.route);
  });
}

function main() {
  const htmlFiles = discoverHtmlFiles(SITE_DIR);
  const routes = sortRoutes(
    htmlFiles.map((htmlFile) => ({
      route: routeFromHtmlPath(htmlFile),
      lastmod: statSync(htmlFile).mtime.toISOString().slice(0, 10),
    })),
  );

  const sitemapPath = join(SITE_DIR, "sitemap.xml");
  const robotsPath = join(SITE_DIR, "robots.txt");

  writeFileSync(sitemapPath, buildSitemapXml(routes), "utf8");
  writeFileSync(robotsPath, buildRobotsTxt(), "utf8");

  console.log(`Generated SEO files for ${routes.length} route(s):`);
  for (const { route } of routes) {
    console.log(`- ${route}`);
  }
}

main();
